def set_run_font(run, name="微软雅黑", size=10.5, bold=False, color=None):
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = name
    if color is not None:
        run.font.color.rgb = color
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:ascii"), name)
    rFonts.set(qn("w:hAnsi"), name)
    rFonts.set(qn("w:eastAsia"), name)


def shade(cell, fill):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tcPr.append(shd)


def set_cell_border(cell):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcBorders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement("w:" + edge)
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:color"), "D5E0DB")
        tcBorders.append(el)
    tcPr.append(tcBorders)


def p_fmt(p, before=0, after=6, line=1.15):
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line


def add_p(doc, text, size=10.5, bold=False, color=INK, before=0, after=6, align=None):
    p = doc.add_paragraph()
    p_fmt(p, before, after)
    if align:
        p.alignment = align
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold, color=color)
    return p


def add_rich(doc, parts, before=0, after=6):
    p = doc.add_paragraph()
    p_fmt(p, before, after)
    for text, bold in parts:
        run = p.add_run(text)
        set_run_font(run, size=10.5, bold=bold, color=INK)
    return p


def h(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    size = {1: 16, 2: 13, 3: 11.5}[level]
    before = {1: 16, 2: 12, 3: 8}[level]
    p_fmt(p, before, 6)
    for run in p.runs:
        set_run_font(run, size=size, bold=True, color=GREEN if level < 3 else INK)
    return p


def bullets(doc, items):
    for t in items:
        p = doc.add_paragraph()
        p_fmt(p, 0, 2)
        p.paragraph_format.left_indent = Cm(0.4)
        run = p.add_run("· " + t)
        set_run_font(run, size=10.5, color=INK)


def table(doc, headers, rows, widths=None):
    tbl = doc.add_table(rows=1 + len(rows), cols=len(headers))
    tbl.autofit = True
    for i, name in enumerate(headers):
        cell = tbl.rows[0].cells[i]
        cell.text = ""
        para = cell.paragraphs[0]
        p_fmt(para, 1, 1)
        run = para.add_run(name)
        set_run_font(run, size=9, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF))
        shade(cell, "096C52")
        set_cell_border(cell)
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            cell = tbl.rows[r + 1].cells[c]
            cell.text = ""
            para = cell.paragraphs[0]
            p_fmt(para, 1, 1)
            run = para.add_run(val)
            set_run_font(run, size=9, color=INK)
            if r % 2 == 1:
                shade(cell, "F4F8F6")
            set_cell_border(cell)
    if widths:
        for row in tbl.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return tbl


def caption(doc, text):
    add_p(doc, text, size=9, color=MUTED, before=2, after=10, align=WD_ALIGN_PARAGRAPH.CENTER)


def image(doc, name, width=15.6):
    path = os.path.join(SHOT, name)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_fmt(p, 4, 2)
    run = p.add_run()
    run.add_picture(path, width=Cm(width))


def header_footer(doc):
    sec = doc.sections[0]
    sec.page_width = Cm(21.0)
    sec.page_height = Cm(29.7)
    sec.left_margin = Cm(1.7)
    sec.right_margin = Cm(1.7)
    sec.top_margin = Cm(1.8)
    sec.bottom_margin = Cm(1.6)
    sec.header_distance = Cm(0.6)
    sec.footer_distance = Cm(0.5)
    hp = sec.header.paragraphs[0]
    hp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    r = hp.add_run("蒙牛活动管理平台  ·  一期产品需求确认与验收")
    set_run_font(r, size=8, color=MUTED)
    fp = sec.footer.paragraphs[0]
    fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r1 = fp.add_run("客户确认稿  ·  第 ")
    set_run_font(r1, size=8, color=MUTED)
    fld1 = OxmlElement("w:fldChar")
    fld1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    fld2 = OxmlElement("w:fldChar")
    fld2.set(qn("w:fldCharType"), "end")
    run = fp.add_run()
    set_run_font(run, size=8, color=MUTED)
    run._r.append(fld1)
    run2 = fp.add_run()
    set_run_font(run2, size=8, color=MUTED)
    run2._r.append(instr)
    run3 = fp.add_run()
    set_run_font(run3, size=8, color=MUTED)
    run3._r.append(fld2)
    r4 = fp.add_run(" 页")
    set_run_font(r4, size=8, color=MUTED)


